/**
 * Fixture-only media: a session whose transcript shows images and files (`?media=1`), and an
 * in-memory stand-in for the host's blob store, attachments and files under a session's cwd,
 * with the same rules as the runtime (`session.attachment.put` / `file.read` / `files.stat`).
 */

const te = new TextEncoder();

function crc32(d: Uint8Array): number {
  let c = ~0;
  for (const b of d) {
    c ^= b;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  }
  return ~c >>> 0;
}

/** A real PNG (stored deflate blocks): a bar chart on a light background. */
export function chartPng(w = 240, h = 150): Uint8Array {
  const bars = [0.35, 0.6, 0.45, 0.8, 0.95, 0.7];
  const raw = new Uint8Array((w * 3 + 1) * h);
  let i = 0;
  for (let y = 0; y < h; y++) {
    raw[i++] = 0;
    for (let x = 0; x < w; x++) {
      const slot = Math.floor((x / w) * bars.length);
      const inBar = x % (w / bars.length) > 6 && x % (w / bars.length) < w / bars.length - 6 && y > h - 12 - bars[slot] * (h - 24) && y < h - 12;
      const axis = y === h - 12 || x === 3;
      const [r, g, b] = axis ? [60, 60, 70] : inBar ? [70 + slot * 25, 120 + slot * 12, 230 - slot * 20] : [246, 247, 250];
      raw[i++] = r;
      raw[i++] = g;
      raw[i++] = b;
    }
  }
  const blocks: number[] = [0x78, 0x01];
  for (let o = 0; o < raw.length; o += 65535) {
    const n = Math.min(65535, raw.length - o);
    blocks.push(o + n >= raw.length ? 1 : 0, n & 255, n >> 8, ~n & 255, (~n >> 8) & 255);
    for (let k = 0; k < n; k++) blocks.push(raw[o + k]);
  }
  let a = 1;
  let bsum = 0;
  for (const v of raw) {
    a = (a + v) % 65521;
    bsum = (bsum + a) % 65521;
  }
  blocks.push(bsum >> 8, bsum & 255, a >> 8, a & 255);
  const out: number[] = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
  const chunk = (type: string, data: number[]) => {
    const td = new Uint8Array([...te.encode(type), ...data]);
    const len = data.length;
    out.push(len >>> 24, (len >> 16) & 255, (len >> 8) & 255, len & 255, ...td);
    const c = crc32(td);
    out.push(c >>> 24, (c >> 16) & 255, (c >> 8) & 255, c & 255);
  };
  chunk("IHDR", [w >>> 24, (w >> 16) & 255, (w >> 8) & 255, w & 255, h >>> 24, (h >> 16) & 255, (h >> 8) & 255, h & 255, 8, 2, 0, 0, 0]);
  chunk("IDAT", blocks);
  chunk("IEND", []);
  return new Uint8Array(out);
}

/** A minimal, valid one-page PDF with a title and a line of text. */
export function simplePdf(title: string, line: string): Uint8Array {
  const stream = `BT /F1 22 Tf 72 720 Td (${title}) Tj ET BT /F1 12 Tf 72 690 Td (${line}) Tj ET 0.2 0.4 0.9 rg 72 520 120 140 re f 0.9 0.5 0.2 rg 210 520 120 100 re f`;
  const objs = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`,
  ];
  let s = "%PDF-1.4\n";
  const offs: number[] = [];
  objs.forEach((o, i) => {
    offs.push(s.length);
    s += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = s.length;
  s += `xref\n0 ${objs.length + 1}\n0000000000 65535 f \n${offs.map((o) => `${String(o).padStart(10, "0")} 00000 n \n`).join("")}`;
  s += `trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return te.encode(s);
}

