const ATTACH_DIR = "/home/you/.marsad/sessions";

interface FileRec {
  bytes: Uint8Array;
  mime: string;
}

const b64 = (bytes: Uint8Array) => {
  let s = "";
  for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  return btoa(s);
};
const unb64 = (s: string) => Uint8Array.from(atob(s), (c) => c.charCodeAt(0));

function sniff(bytes: Uint8Array, name: string): string {
  const head = new TextDecoder().decode(bytes.subarray(0, 64)).trimStart().toLowerCase();
  if (bytes[0] === 0x89 && bytes[1] === 0x50) return "image/png";
  if (head.startsWith("%pdf-")) return "application/pdf";
  if (head.startsWith("<svg")) return "image/svg+xml";
  const ext = name.toLowerCase().split(".").pop();
  const m: Record<string, string> = { html: "text/html", csv: "text/csv", md: "text/markdown", json: "application/json", txt: "text/plain", ts: "text/plain", jpg: "image/jpeg", gif: "image/gif", webp: "image/webp", mp3: "audio/mpeg" };
  if (ext && m[ext]) return m[ext];
  return bytes.includes(0) ? "application/octet-stream" : "text/plain";
}

/** Blob ids of the fixture images. */
export const BLOB_CHART = "c".repeat(64);

export class FixtureFiles {
  /** `<session id>` → absolute path → file. */
  private files = new Map<string, Map<string, FileRec>>();
  private blobs = new Map<string, FileRec>([[BLOB_CHART, { bytes: chartPng(), mime: "image/png" }]]);
  private uploads = new Map<string, { name: string; size: number; parts: Uint8Array[]; got: number }>();

  /** Seed the media session's folder. */
  seed(session: string, cwd: string) {
    const m = this.of(session);
    const put = (rel: string, bytes: Uint8Array) => m.set(`${cwd}/${rel}`, { bytes, mime: sniff(bytes, rel) });
    put("out/chart.svg", te.encode(CHART_SVG));
    put("report.pdf", simplePdf("Quarterly report", "Revenue grew 45% in Q4."));
    put("preview.html", te.encode(PREVIEW_HTML));
    put("data.csv", te.encode(DATA_CSV));
    put("README.md", te.encode(README_MD));
    put("config.json", te.encode(`{"chart":{"type":"bar","series":[1200,1550,1390,2010]}}`));
    put("notes.bin", new Uint8Array([0, 1, 2, 3, 250, 251]));
    put("out/chart.png", chartPng());
    m.set(`${ATTACH_DIR}/${session}/attachments/u1/sketch.png`, { bytes: chartPng(120, 80), mime: "image/png" });
  }

  private of(session: string) {
    let m = this.files.get(session);
    if (!m) this.files.set(session, (m = new Map()));
    return m;
  }

  /** Absolute path of `p` inside the session's roots, or an error (traversal, outside). */
  private resolve(session: string, cwd: string | null, p: string, outside: boolean): string {
    const home = "/home/you";
    const root = (cwd ?? "").replace(/^~/, home);
    const abs = p.startsWith("/") ? p : p.startsWith("~") ? p.replace(/^~/, home) : `${root}/${p}`;
    const parts: string[] = [];
    for (const seg of abs.split("/")) {
      if (!seg || seg === ".") continue;
      if (seg === "..") parts.pop();
      else parts.push(seg);
    }
    const norm = `/${parts.join("/")}`;
    const roots = [root, `${ATTACH_DIR}/${session}/attachments`];
    if (!outside && !roots.some((r) => r && (norm === r || norm.startsWith(`${r}/`)))) throw Object.assign(new Error(`${p} is outside the session's folder (open it explicitly to read it)`), { code: "invalid_params" });
    return norm;
  }

  private lookup(session: string, path: string): FileRec | undefined {
    const m = this.of(session);
    return m.get(path) ?? m.get(path.replace(/^\/home\/you/, "~"));
  }

  read(r: FileReadRequest, cwd: string | null): FileChunk {
    let rec: FileRec | undefined;
    let path: string;
    if (r.blob) {
      if (!/^[0-9a-f]{64}$/.test(r.blob)) throw Object.assign(new Error("bad blob id"), { code: "invalid_params" });
      rec = this.blobs.get(r.blob);
      path = `${ATTACH_DIR}/${r.id}/blobs/${r.blob}`;
    } else {
      path = this.resolve(r.id, cwd, r.path ?? "", r.outside);
      rec = this.lookup(r.id, path);
    }
    if (!rec) throw Object.assign(new Error(`no such file: ${r.blob ?? r.path}`), { code: "invalid_params" });
    const offset = Math.min(Number(r.offset), rec.bytes.length);
    const len = Math.min(Number(r.length ?? 4 << 20), 4 << 20, rec.bytes.length - offset);
    return { path, mime: rec.mime, size: rec.bytes.length, offset, data: b64(rec.bytes.subarray(offset, offset + len)), eof: offset + len >= rec.bytes.length };
  }

  stat(session: string, cwd: string | null, paths: string[]): FilesStatReply {
    const files = [];
    for (const p of paths) {
      let abs: string;
      try {
        abs = this.resolve(session, cwd, p, false);
      } catch {
        continue;
      }
      const rec = this.lookup(session, abs);
      if (rec) files.push({ path: p, resolved: abs, size: rec.bytes.length, mime: rec.mime, is_dir: false, modified_ms: null });
    }
    return { files };
  }

  put(r: AttachmentPut): AttachmentPutReply {
    if (!/^[a-z0-9]{8,32}$/.test(r.upload)) throw Object.assign(new Error("bad upload id"), { code: "invalid_params" });
    if (r.size > 50 * 1024 * 1024) throw Object.assign(new Error("the file is larger than 50 MiB"), { code: "invalid_params" });
    const key = `${r.id}/${r.upload}`;
    if (r.offset === 0) this.uploads.set(key, { name: r.name, size: r.size, parts: [], got: 0 });
    const u = this.uploads.get(key);
    if (!u) throw Object.assign(new Error("unknown upload (start at offset 0)"), { code: "invalid_params" });
    if (u.got !== r.offset) throw Object.assign(new Error(`expected offset ${u.got}, got ${r.offset}`), { code: "invalid_params" });
    const bytes = unb64(r.data);
    u.parts.push(bytes);
    u.got += bytes.length;
    if (!r.last) return { received: u.got, attachment: null };
    const all = new Uint8Array(u.got);
    let at = 0;
    for (const p of u.parts) {
      all.set(p, at);
      at += p.length;
    }
    this.uploads.delete(key);
    const name = r.name.split(/[\\/]/).pop() || "file";
    const path = `${ATTACH_DIR}/${r.id}/attachments/${r.upload}/${name}`;
    const mime = sniff(all, name);
    this.of(r.id).set(path, { bytes: all, mime });
    const a: Attachment = { name, mime, size: all.length, path };
    return { received: u.got, attachment: a };
  }
}

