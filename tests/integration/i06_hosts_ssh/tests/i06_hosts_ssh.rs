/// Seeded localhost entry is protected: is_local=true, removable=false,
/// remove → CannotRemoveLocalhost.
#[test]
fn part_a_localhost_is_protected() {
    let runner = Box::new(FakeSshRunner::new());
    let mut reg = HostRegistry::new(runner);

    let local = reg
        .list()
        .iter()
        .find(|h| h.is_local)
        .cloned()
        .expect("localhost must be seeded");

    assert!(local.is_local, "is_local must be true for seeded localhost");
    assert!(
        !local.removable,
        "removable must be false for seeded localhost"
    );

    let err = reg
        .remove(&local.id)
        .expect_err("remove localhost must fail");
    assert!(
        matches!(err, HostError::CannotRemoveLocalhost),
        "expected CannotRemoveLocalhost, got {:?}",
        err
    );
}

/// Add a remote host; it appears in list(); remove it; it disappears.
#[test]
fn part_a_add_and_remove_remote_host() {
    let runner = Box::new(FakeSshRunner::new());
    let mut reg = HostRegistry::new(runner);

    let id = {
        let host = reg
            .add("ci-runner", "ci@ci-runner.example.com")
            .expect("add must succeed");
        assert_eq!(host.label, "ci-runner");
        assert_eq!(host.target, "ci@ci-runner.example.com");
        assert!(!host.is_local);
        assert!(host.removable);
        // New hosts start Reconnecting until a successful health_check.
        assert_eq!(
            host.status,
            HostStatus::Reconnecting,
            "new remote must start in Reconnecting"
        );
        host.id.clone()
    };

    assert!(
        reg.list().iter().any(|h| h.id == id),
        "added host must appear in list"
    );

    reg.remove(&id).expect("remove must succeed");
    assert!(
        !reg.list().iter().any(|h| h.id == id),
        "removed host must not appear in list"
    );
}

/// health_check via FakeSshRunner → Connected on scripted success.
#[test]
fn part_a_health_check_connected_on_ok() {
    let mut fake = FakeSshRunner::new();
    fake.respond("alice@good.example.com", Ok("ok".to_string()));
    let mut reg = HostRegistry::new(Box::new(fake));

    let id = reg
        .add("good", "alice@good.example.com")
        .unwrap()
        .id
        .clone();
    let status = reg.health_check(&id);
    assert_eq!(
        status,
        HostStatus::Connected,
        "FakeSshRunner Ok → Connected"
    );
}

