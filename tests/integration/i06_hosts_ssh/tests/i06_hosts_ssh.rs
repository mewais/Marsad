//! Integration scenario i06_hosts_ssh — host registry + SSH.
//!
//! Part A: Deterministic ssh-config parse + HostRegistry contract (always runs).
//! Part B: Real localhost-as-SSH smoke (skip-guarded; uses BatchMode=yes so it never hangs).

use marsad_hosts::{parse_ssh_config, FakeSshRunner, HostError, HostRegistry, HostStatus};

// ─────────────────────────────────────────────────────────────────────────────
// Part A — DETERMINISTIC
// ─────────────────────────────────────────────────────────────────────────────

/// Parse a realistic multi-Host ~/.ssh/config with HostName/User/IdentityFile,
/// comments, blank lines, and a wildcard `Host *` block.
#[test]
fn part_a_parse_ssh_config_realistic() {
    let config = r#"
# ~/.ssh/config — generated by Marsad i06 integration test

# Jump host for the internal network
Host jumpbox
    HostName jumpbox.internal.example.com
    User jdoe
    IdentityFile ~/.ssh/id_ed25519

Host devbox
    HostName 10.10.1.42
    User developer
    IdentityFile ~/.ssh/id_rsa

# Production deployment target
Host prod-web-01
    HostName prod-web-01.example.com
    User deploy
    IdentityFile ~/.ssh/deploy_ed25519

# Wildcard catch-all — must be kept as-is
Host *
    ServerAliveInterval 60
    StrictHostKeyChecking accept-new
"#;

    let entries = parse_ssh_config(config);

    // Must produce exactly 4 entries (including the wildcard Host *).
    assert_eq!(
        entries.len(),
        4,
        "expected 4 Host blocks (jumpbox, devbox, prod-web-01, *); got {:?}",
        entries.iter().map(|e| &e.alias).collect::<Vec<_>>()
    );

    // ── jumpbox ──────────────────────────────────────────────────────────────
    let jumpbox = entries
        .iter()
        .find(|e| e.alias == "jumpbox")
        .expect("jumpbox entry not found");
    assert_eq!(
        jumpbox.hostname.as_deref(),
        Some("jumpbox.internal.example.com"),
        "jumpbox HostName mismatch"
    );
    assert_eq!(
        jumpbox.user.as_deref(),
        Some("jdoe"),
        "jumpbox User mismatch"
    );
    assert_eq!(
        jumpbox.identity_file.as_deref(),
        Some("~/.ssh/id_ed25519"),
        "jumpbox IdentityFile mismatch"
    );

    // ── devbox ───────────────────────────────────────────────────────────────
    let devbox = entries
        .iter()
        .find(|e| e.alias == "devbox")
        .expect("devbox entry not found");
    assert_eq!(devbox.hostname.as_deref(), Some("10.10.1.42"));
    assert_eq!(devbox.user.as_deref(), Some("developer"));
    assert_eq!(devbox.identity_file.as_deref(), Some("~/.ssh/id_rsa"));

    // ── prod-web-01 ──────────────────────────────────────────────────────────
    let prod = entries
        .iter()
        .find(|e| e.alias == "prod-web-01")
        .expect("prod-web-01 entry not found");
    assert_eq!(
        prod.hostname.as_deref(),
        Some("prod-web-01.example.com")
    );
    assert_eq!(prod.user.as_deref(), Some("deploy"));
    assert_eq!(
        prod.identity_file.as_deref(),
        Some("~/.ssh/deploy_ed25519")
    );

    // ── wildcard * ───────────────────────────────────────────────────────────
    let wildcard = entries
        .iter()
        .find(|e| e.alias == "*")
        .expect("wildcard Host * entry not found");
    // Wildcard block has no HostName/User/IdentityFile in this config;
    // ServerAliveInterval is not a recognised directive and should be silently ignored.
    assert_eq!(wildcard.alias, "*");
    assert!(
        wildcard.hostname.is_none(),
        "wildcard must have no HostName"
    );
    assert!(wildcard.user.is_none(), "wildcard must have no User");
    assert!(
        wildcard.identity_file.is_none(),
        "wildcard must have no IdentityFile"
    );
}

/// Comments and blank lines produce no entries; partial blocks (missing HostName)
/// are tolerated and produce entries with None fields.
#[test]
fn part_a_parse_comments_and_blank_lines() {
    let config = "# just a comment\n\n# another comment\n";
    let entries = parse_ssh_config(config);
    assert!(
        entries.is_empty(),
        "comment-only config must yield no entries"
    );
}

#[test]
fn part_a_parse_partial_block_missing_fields() {
    // Host with no HostName/User/IdentityFile — fields must be None, not error.
    let config = "Host minimalhost\n";
    let entries = parse_ssh_config(config);
    assert_eq!(entries.len(), 1);
    assert_eq!(entries[0].alias, "minimalhost");
    assert!(entries[0].hostname.is_none());
    assert!(entries[0].user.is_none());
    assert!(entries[0].identity_file.is_none());
}

