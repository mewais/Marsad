/// add with a duplicate label → DuplicateLabel.
#[test]
fn part_a_duplicate_label_error() {
    let runner = Box::new(FakeSshRunner::new());
    let mut reg = HostRegistry::new(runner);
    reg.add("builder", "ci@builder.example.com")
        .expect("first add must succeed");
    let err = reg
        .add("builder", "ci@other.example.com")
        .expect_err("duplicate label must fail");
    match err {
        HostError::DuplicateLabel(label) => assert_eq!(label, "builder"),
        other => panic!("expected DuplicateLabel, got {:?}", other),
    }
}

/// add with a malformed target (no @, empty user, empty host) → MalformedTarget.
#[test]
fn part_a_malformed_target_errors() {
    let cases: &[&str] = &[
        "",             // empty
        "nousernoslash",// no @
        "@host",        // missing user
        "user@",        // missing host
        "@",            // both missing
    ];

    for &bad in cases {
        let runner = Box::new(FakeSshRunner::new());
        let mut reg = HostRegistry::new(runner);
        let err = reg
            .add("host", bad)
            .expect_err(&format!("target {:?} must fail", bad));
        assert!(
            matches!(err, HostError::MalformedTarget(_)),
            "target {:?} → expected MalformedTarget, got {:?}",
            bad,
            err
        );
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Part B — LIVE localhost SSH smoke (skip-guarded)
// ─────────────────────────────────────────────────────────────────────────────

/// Check whether `ssh` binary is on PATH.
fn ssh_available() -> bool {
    std::process::Command::new("ssh")
        .arg("-V")
        .output()
        .is_ok()
}

/// Test passwordless ssh to localhost with BatchMode=yes, ConnectTimeout=5.
/// Returns true only if the exit status is 0.
fn passwordless_localhost_ssh_works() -> bool {
    match std::process::Command::new("ssh")
        .args([
            "-o",
            "BatchMode=yes",
            "-o",
            "ConnectTimeout=5",
            "localhost",
            "true",
        ])
        .status()
    {
        Ok(s) => s.success(),
        Err(_) => false,
    }
}

/// Part B: real SSH smoke over localhost.
///
/// Skip conditions (in order):
///   1. `ssh` not on PATH  → skip
///   2. `ssh -o BatchMode=yes -o ConnectTimeout=5 localhost true` fails → skip
///
/// If both checks pass: use `SshStdio` to run `echo marsad-i06-smoke` over real
/// ssh to localhost and assert we get the expected line back.
///
/// `TEARDOWN`: SshStdio::close() kills the ssh child and drops all handles.
/// No tmux sessions or temp files are created; nothing to orphan.
#[test]
fn part_b_live_localhost_ssh_smoke() {
    // ── Guard 1: ssh binary ───────────────────────────────────────────────────
    if !ssh_available() {
        eprintln!("SKIP: ssh binary not found — skipping Part B live localhost SSH smoke");
        return;
    }

    // ── Guard 2: passwordless ssh to localhost ────────────────────────────────
    if !passwordless_localhost_ssh_works() {
        eprintln!(
            "SKIP: passwordless ssh to localhost unavailable \
             (BatchMode=yes failed) — skipping Part B live localhost SSH smoke"
        );
        return;
    }

    // ── Live smoke ────────────────────────────────────────────────────────────
    use marsad_transport::{SshStdio, Transport};

    let expected_token = "marsad-i06-smoke";
    // Run a trivial remote command: echo the token to stdout and exit cleanly.
    let remote_cmd = format!("echo {expected_token}");

    let mut transport = SshStdio::new("localhost", remote_cmd);

    transport
        .connect()
        .expect("SshStdio::connect to localhost must succeed");

    // Read the single output line.
    let line = transport
        .recv_line()
        .expect("recv_line must not error")
        .expect("recv_line must return Some (got None/EOF before the echo line)");

    assert_eq!(
        line.trim(),
        expected_token,
        "live ssh echo output mismatch: expected {:?}, got {:?}",
        expected_token,
        line
    );

    // TEARDOWN: close kills the ssh child.
    transport.close().expect("close must succeed");

    eprintln!("Part B: real localhost SSH smoke PASSED — echo round-trip confirmed");
}
